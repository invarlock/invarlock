"""Generate the Unicode 3.2 Nameprep tables used by CPython's IDNA2003 codec.

Maintenance tool only; the Rust runtime uses these committed tables directly.
"""
from pathlib import Path
import stringprep
from unicodedata import ucd_3_2_0 as u

lines=['// Unicode 3.2 Nameprep tables; generated by tools/generate_idna.py.']
lines.append('pub const MAPPING: &[(u32,&[u32])] = &[')
for cp in range(0x110000):
    if 0xD800<=cp<=0xDFFF:continue
    c=chr(cp)
    mapped='' if stringprep.in_table_b1(c) else u.normalize('NFKD',stringprep.map_table_b2(c))
    if mapped!=c:lines.append(f'({cp},&[{",".join(str(ord(c)) for c in mapped)}]),')
lines.append('];')
lines.append('pub const COMBINING: &[(u32,u8)] = &[')
for cp in range(0x110000):
    if cc:=u.combining(chr(cp)):lines.append(f'({cp},{cc}),')
lines.append('];')
lines.append('pub const COMPOSITION: &[((u32,u32),u32)] = &[')
compositions=[]
for cp in range(0x110000):
    d=u.decomposition(chr(cp)).split()
    if len(d)==2 and not d[0].startswith('<'):
        pair=tuple(int(v,16) for v in d)
        if u.normalize('NFC',''.join(map(chr,pair)))==chr(cp):compositions.append((pair,cp))
for (a,b),cp in sorted(compositions):lines.append(f'(({a},{b}),{cp}),')
lines.append('];')
checks=[('PROHIBITED',lambda c:any(f(c) for f in [stringprep.in_table_c12,stringprep.in_table_c22,stringprep.in_table_c3,stringprep.in_table_c4,stringprep.in_table_c5,stringprep.in_table_c6,stringprep.in_table_c7,stringprep.in_table_c8,stringprep.in_table_c9])),('RANDAL',stringprep.in_table_d1),('LEFT',stringprep.in_table_d2)]
for name,check in checks:
    lines.append(f'pub const {name}: &[(u32,u32)] = &[');start=None
    for cp in range(0x110001):
        matches=cp<0x110000 and check(chr(cp))
        if matches and start is None:start=cp
        if not matches and start is not None:lines.append(f'({start},{cp-1}),');start=None
    lines.append('];')
(Path(__file__).resolve().parents[1]/'src/idna_tables.rs').write_text('\n'.join(lines)+'\n')
