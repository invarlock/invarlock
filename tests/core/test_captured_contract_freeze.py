@pytest.mark.parametrize(
    "mutation",
    ["unknown", "path", "format", "pin", "override", "run_digest", "policy_digest"],
)
def test_resigned_normalized_request_fails_before_presentation_or_replay(
    tmp_path, monkeypatch, mutation
):
    pack, options = _pack(tmp_path), _verify_options(tmp_path)
    request = _value("request-pass.json")
    source = request["comparison"]["baseline"]
    if mutation == "unknown":
        request["unknown"] = True
    elif mutation == "path":
        source["path"] = "/outside/request.json"
    elif mutation == "format":
        request["format"] = "invarlock/evaluation-request-v2-normalized"
    elif mutation == "override":
        source["run_id"] = "override"
    elif mutation in {"pin", "run_digest"}:
        source["expected_run_digest" if mutation == "pin" else "run_digest"] = (
            "sha256:" + "0" * 64
        )
    else:
        request["comparison"]["policy_digest"] = "sha256:" + "0" * 64
    _write(pack / "request.json", _canonical(request))
    _rebind(pack)
    forbidden = Mock(side_effect=AssertionError("invalid snapshot reached consumer"))
    monkeypatch.setattr(reporting, "_view", forbidden)
    monkeypatch.setattr(verification, "compare_runs", forbidden)
    with pytest.raises(evidence_reporting.EvidenceReportError):
        evidence_reporting.render_evidence(pack)
    with pytest.raises(verification.CapturedVerificationError) as failure:
        verification.verify_captured_evidence(pack, **options)
    assert failure.value.exit_code == (
        6 if mutation in {"run_digest", "policy_digest"} else 4
    )
    assert _authenticate(pack, options).ok
    forbidden.assert_not_called()


@pytest.mark.parametrize(
    "field",
    ["source", "run_id", "artifact_digest", "score_provenance", "source_digest"],
)
def test_resigned_import_intent_must_agree_with_run(tmp_path, monkeypatch, field):
    pack, options = _pack(tmp_path), _verify_options(tmp_path)
    baseline, request, report = (
        _value("baseline.json"),
        _value("request-pass.json"),
        _value("comparison-pass.json"),
    )
    baseline["source_digest"] = "sha256:" + "3" * 64
    source = {
        "adapter": "jsonl",
        **{
            k: baseline[k]
            for k in ("source", "run_id", "artifact_digest", "score_provenance")
        },
        "run_digest": _sha(_canonical(baseline)),
    }
    request["comparison"]["baseline"] = source
    report["bindings"]["baseline"] = source["run_digest"]
    for path, value in [
        ("records/baseline.json", baseline),
        ("request.json", request),
        ("reports/evaluation.report.json", report),
    ]:
        _write(pack / path, _canonical(value))
    _rebind(pack)
    # Establish that this imported intent is valid before contradicting one field.
    with contracts.captured_snapshot(pack) as snapshot:
        contracts.load_payloads(snapshot)
    if field == "source_digest":
        baseline[field] = None
        source["run_digest"] = _sha(_canonical(baseline))
        report["bindings"]["baseline"] = source["run_digest"]
    else:
        source[field] = {
            "source": {"name": "other", "version": "1"},
            "run_id": "other",
            "artifact_digest": "sha256:" + "4" * 64,
            "score_provenance": {},
        }[field]
    for path, value in [
        ("records/baseline.json", baseline),
        ("request.json", request),
        ("reports/evaluation.report.json", report),
    ]:
        _write(pack / path, _canonical(value))
    _rebind(pack)
    forbidden = Mock(side_effect=AssertionError("inconsistent source reached consumer"))
    monkeypatch.setattr(reporting, "_view", forbidden)
    monkeypatch.setattr(verification, "compare_runs", forbidden)
    with pytest.raises(evidence_reporting.EvidenceReportError):
        evidence_reporting.render_evidence(pack)
    with pytest.raises(verification.CapturedVerificationError) as failure:
        verification.verify_captured_evidence(pack, **options)
    assert failure.value.exit_code == 6
    assert _authenticate(pack, options).ok
    forbidden.assert_not_called()


