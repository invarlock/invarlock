@pytest.mark.parametrize("variant", ["success", "failure"])
def test_frozen_keygen_setup(tmp_path, monkeypatch, variant):
    directory = tmp_path / "keys"
    existing = variant == "failure"
    role = "verifier" if existing else "signer"
    expected_files = {
        "private.pem": _pem(role),
        "public.pem": CORPUS["test_keys"][role]["public_key_pem"].encode(),
    }
    if existing:
        directory.mkdir()
        for name, raw in expected_files.items():
            (directory / name).write_bytes(raw)

    # RFC 8032 test 1, documented in the corpus; never use generated CLI values
    # to construct the expected fingerprint or key material.
    key = _key("signer")
    assert (
        _sha(
            key.public_key().public_bytes(
                serialization.Encoding.Raw, serialization.PublicFormat.Raw
            )
        )
        == CORPUS["test_keys"]["signer"]["fingerprint"]
    )
    generate = Mock(return_value=key)
    monkeypatch.setattr(Ed25519PrivateKey, "generate", generate)
    result = RUNNER.invoke(app, ["evaluate", "--keygen", str(directory), "--json"])
    assert result.exit_code == (2 if existing else 0), result.output
    assert result.stderr == ""
    stdout = result.stdout
    if existing:
        generate.assert_not_called()
    else:
        generate.assert_called_once_with()
        for name in expected_files:
            path = str(directory / name)
            assert stdout.count(path) == 1
            stdout = stdout.replace(path, f"<root>/keys/{name}")
    # Typer adds one framing LF after the canonical JSON's own trailing LF.
    assert stdout.encode() == _raw(f"setup-keygen-{variant}.json") + b"\n"
    assert set(tmp_path.iterdir()) == {directory}
    assert {path.name: path.read_bytes() for path in directory.iterdir()} == (
        expected_files
    )


@pytest.mark.parametrize("variant", ["success", "output-success", "failure"])
def test_frozen_freeze_cases_setup(tmp_path, monkeypatch, variant):
    # Literal approved membership, with its independently computed SHA-256.
    approved = (
        b'{"cases":[{"expected":"yes","id":"a","input":"first","metadata":{}},'
        b'{"expected":"yes","id":"b","input":"second","metadata":{}}],'
        b'"format":"invarlock/evaluation-case-set-v1"}\n'
    )
    assert _canonical(json.loads(approved)) == approved
    assert _sha(approved) == (
        "sha256:799d0a3b15d9a811ea2a9d118af0333aeb8e103bcd95cc62832a34c57ccdef14"
    )
    authored = json.loads(approved)
    authored["cases"].reverse()
    source = tmp_path / "planned.json"
    source_raw = json.dumps(authored, indent=2).encode()
    source.write_bytes(source_raw)
    output = tmp_path / "canonical.json"
    expected_files = {source: source_raw}
    if variant == "failure":
        expected_files[output] = b"approved destination: do not overwrite\n"
        output.write_bytes(expected_files[output])

    monkeypatch.chdir(tmp_path)
    # Pin only the staging filename; keep real no-replace filesystem publication.
    token_hex = Mock(return_value="0" * 32)
    monkeypatch.setattr(contracts.secrets, "token_hex", token_hex)
    args = ["evaluate", "--freeze-cases", str(source), "--json"]
    if variant != "success":
        args.extend(["--case-set-output", str(output)])
    result = RUNNER.invoke(app, args)
    assert result.exit_code == (2 if variant == "failure" else 0), result.output
    assert result.stderr == ""
    stdout = result.stdout
    if variant == "output-success":
        assert stdout.count(str(output)) == 1
        stdout = stdout.replace(str(output), "<root>/canonical.json")
        expected_files[output] = approved
    assert stdout.encode() == _raw(f"setup-freeze-cases-{variant}.json") + b"\n"
    if variant == "success":
        token_hex.assert_not_called()
    else:
        token_hex.assert_called_once_with(16)
    assert {path: path.read_bytes() for path in tmp_path.iterdir()} == expected_files
